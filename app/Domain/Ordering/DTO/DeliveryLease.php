<?php

declare(strict_types=1);

namespace App\Domain\Ordering\DTO;

/**
 * Аренда на выдачу заказа с fencing-токеном.
 *
 * Взаимное исключение строится на аренде, а не на статусе: переход
 * delivering -> delivering машина состояний не разрешает, поэтому по статусу
 * невозможно отличить «я начал выдачу» от «выдачу уже ведёт другой воркер».
 * Аренда отвечает на этот вопрос однозначно: аренду получил ровно один.
 *
 * Токен обязателен во ВСЕХ последующих записях этого воркера. Если аренда
 * успела протухнуть и её перехватил другой процесс, наши записи затронут ноль
 * строк — и воркер тихо выйдет, а не затрёт чужую работу.
 */
final readonly class DeliveryLease
{
    public function __construct(
        public int $orderId,
        public string $token,
    ) {}
}
