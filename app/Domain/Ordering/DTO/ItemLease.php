<?php

declare(strict_types=1);

namespace App\Domain\Ordering\DTO;

/**
 * Аренда на выдачу ПОЗИЦИИ с fencing-токеном.
 *
 * Взаимное исключение строится на аренде, а не на статусе: переход
 * delivering -> delivering машина состояний не разрешает, поэтому по статусу
 * невозможно отличить «я начал выдачу» от «выдачу уже ведёт другой воркер».
 * Аренда отвечает на это однозначно: её получил ровно один.
 *
 * Аренда именно на позицию, а не на заказ. Иначе выдача заказа становится
 * последовательной: пока первая позиция ждёт залипшего поставщика, вторая
 * не может даже начать, хотя её товар лежит в собственном пуле.
 */
final readonly class ItemLease
{
    public function __construct(
        public int $itemId,
        public string $token,
    ) {}
}
