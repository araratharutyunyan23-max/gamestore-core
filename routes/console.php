<?php

declare(strict_types=1);

use Illuminate\Support\Facades\Schedule;

/*
| Восстановление ведётся от ИНБОКСА, а не от статуса заказа: заказ, застрявший
| из-за потерянной задачи, не виден ни одному статусному фильтру, а событию
| с applied_at IS NULL — виден.
|
| withoutOverlapping обязателен: два одновременных прохода поставили бы каждое
| событие дважды. Джобы идемпотентны, но лишняя работа под нагрузкой не нужна.
*/
Schedule::command('payments:drain-unapplied')
    ->everyMinute()
    ->withoutOverlapping();

/*
| Судьба обращения, закончившегося неизвестностью, выясняется только повтором
| probe по ТОМУ ЖЕ request_id. Новый идентификатор здесь не создаётся никогда —
| он означал бы покупку второго кода.
*/
Schedule::command('delivery:resolve-unknown')
    ->everyMinute()
    ->withoutOverlapping();

/*
| Подметальщик НЕ имеет собственной логики выдачи: он ставит ту же задачу,
| что и обычный путь после оплаты. Отдельный путь восстановления расходится
| с основным ровно в тех переходах, которые никто не догадался проверить,
| и становится источником второй выдачи.
*/
Schedule::command('orders:sweep-stuck')
    ->everyMinute()
    ->withoutOverlapping();

/*
| Быстрая сверка — ежеминутно. Её не было в расписании вовсе, и это ломало
| ровно то, ради чего она написана: пять детекторов денежных расхождений
| (оплачен-не-выдан, выдан-не-оплачен, зависшее событие, нерешённое обращение
| к поставщику, несовпадение суммы) срабатывали только по ручному запросу
| эндпоинта или раз в сутки ночью. Расхождение в деньгах, найденное через
| двадцать часов, — это уже не наблюдаемость, а археология.
|
| Она же держит /health зелёным: свежесть сверки там измеряется именно
| по этим прогонам.
|
| Повторных находок не создаёт: на (вид, субъект) висит частичный уникальный
| индекс среди неразрешённых, вставка идёт через insertOrIgnore.
*/
Schedule::command('shop:reconcile')
    ->everyMinute()
    ->withoutOverlapping();

/*
| Полная сверка — ночью: три её проверки идут по всей истории и ежеминутно
| не нужны, расхождение такого рода не появляется за минуту.
*/
Schedule::command('shop:reconcile --full')
    ->dailyAt('03:00')
    ->withoutOverlapping();
